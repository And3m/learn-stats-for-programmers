/**
 * Regenerates `src/content/lesson-components.ts` from the MDX files on disk.
 *
 * The map has to consist of static imports so the bundler can see every lesson;
 * writing it by hand across 55 files is a reliable source of typos, so it is
 * generated instead. Run `npm run content:map` after adding a lesson.
 */

import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const chaptersDir = path.join(root, "src", "content", "chapters");
const outputPath = path.join(root, "src", "content", "lesson-components.ts");

function identifier(chapterSlug, lessonSlug) {
  return `${chapterSlug}-${lessonSlug}`
    .split(/[^a-z0-9]+/i)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

const entries = [];

for (const chapterSlug of (await readdir(chaptersDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()) {
  const files = (await readdir(path.join(chaptersDir, chapterSlug)))
    .filter((name) => name.endsWith(".mdx"))
    .sort();

  for (const file of files) {
    const lessonSlug = file.replace(/\.mdx$/, "");
    entries.push({
      key: `${chapterSlug}/${lessonSlug}`,
      name: identifier(chapterSlug, lessonSlug),
      importPath: `@/content/chapters/${chapterSlug}/${lessonSlug}.mdx`,
    });
  }
}

const header = `// GENERATED BY scripts/gen-lesson-components.mjs — do not edit by hand.
// Run \`npm run content:map\` after adding or renaming a lesson.

import type { ComponentType } from "react";

`;

const imports = entries.map((e) => `import ${e.name} from "${e.importPath}";`).join("\n");

const body = `

export const lessonComponents: Record<string, ComponentType> = {
${entries.map((e) => `  "${e.key}": ${e.name},`).join("\n")}
};
`;

await writeFile(outputPath, header + imports + body, "utf8");
console.log(`Wrote ${entries.length} lesson${entries.length === 1 ? "" : "s"} to ${path.relative(root, outputPath)}`);
